"""Write the exported LIBERO scenes into the cobot-arm package: one ES module per scene
(physics MJCF, settled episode, render pack and its gzip+base64 binary) and the test
fixtures (reference expert replay and robosuite's own camera images)."""
import base64, gzip, json, os, shutil, sys, tempfile

OUT = os.environ.get("LIBERO_EXPORT_OUT") or os.path.join(tempfile.gettempdir(), "libero-export")
PACKAGE = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VENDOR = os.path.join(PACKAGE, "ui/workbench/vendor/libero")
FIXTURES = os.path.join(PACKAGE, "tests/fixtures/libero")
LIMIT = 8 * 1024 * 1024


def main():
    os.makedirs(VENDOR, exist_ok=True)
    os.makedirs(FIXTURES, exist_ok=True)
    for task in ("drawer", "microwave"):
        folder = os.path.join(OUT, task)
        episode = json.load(open(os.path.join(folder, "episode.json")))
        reference = episode.pop("reference")
        render = json.load(open(os.path.join(folder, "render.json")))
        render.pop("source_triangles", None)
        binary = open(os.path.join(folder, "render.bin"), "rb").read()
        packed = base64.b64encode(gzip.compress(binary, 9, mtime=0)).decode("ascii")
        physics = open(os.path.join(folder, "physics.xml")).read()
        module = (
            f"// Generated by tools/libero from LIBERO {episode['libero_revision']} libero_90 task "
            f"{episode['task_id']} on robosuite {episode['versions']['robosuite']}, MuJoCo {episode['versions']['mujoco']}. Do not edit.\n"
            f"export const PHYSICS = {json.dumps(physics)}\n"
            f"export const EPISODE = {json.dumps(episode, separators=(',', ':'))}\n"
            f"export const RENDER = {json.dumps(render, separators=(',', ':'))}\n"
            f"export const RENDER_BIN = '{packed}'\n"
        )
        path = os.path.join(VENDOR, f"{task}.js")
        open(path, "w").write(module)
        size = os.path.getsize(path)
        assert size < LIMIT, (path, size)
        json.dump({"task": task, "task_id": episode["task_id"], **reference},
                  open(os.path.join(FIXTURES, f"{task}-reference.json"), "w"), separators=(",", ":"))
        for view in ("external", "wrist"):
            shutil.copy(os.path.join(folder, f"robosuite-{view}.png"), os.path.join(FIXTURES, f"{task}-robosuite-{view}.png"))
        print(task, "module", size, "bytes")


if __name__ == "__main__":
    main()
