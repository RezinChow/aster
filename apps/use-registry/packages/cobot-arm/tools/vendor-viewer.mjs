// Vendor the workbench viewer dependencies into ui/workbench/vendor and ui/workbench/fonts.
//
//   npm pack three@0.180.0 lucide@0.468.0 @fontsource/ubuntu@5.3.0  (then untar each)
//   node tools/vendor-viewer.mjs <three package> <lucide package> <@fontsource/ubuntu package>
//
// three.js (MIT): the minified module build is unmodified. OrbitControls imports
// the bare specifier 'three'; the view has no import map, so the copy imports
// ./three.module.min.js instead. Nothing else changes.
// Lucide (ISC): the icons the workbench uses, rendered to SVG markup.
// Ubuntu (Ubuntu Font Licence 1.0): the latin 400, 500 and 700 woff2 files.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const [three, lucide, ubuntu] = process.argv.slice(2)
if (!three || !lucide || !ubuntu) {
  console.error('usage: node tools/vendor-viewer.mjs <three> <lucide> <@fontsource/ubuntu>')
  process.exit(2)
}
const root = new URL('../ui/workbench/', import.meta.url)
const into = (path) => {
  const url = new URL(path, root)
  mkdirSync(new URL('./', url), { recursive: true })
  return url
}

for (const file of ['three.core.min.js', 'three.module.min.js']) {
  copyFileSync(join(three, 'build', file), into(`vendor/three/${file}`))
}
const controls = readFileSync(join(three, 'examples/jsm/controls/OrbitControls.js'), 'utf8')
const specifier = "} from 'three';"
if (controls.split(specifier).length !== 2) throw new Error('OrbitControls import of three not found once')
writeFileSync(into('vendor/three/OrbitControls.js'), controls.replace(specifier, "} from './three.module.min.js';"))
copyFileSync(join(three, 'LICENSE'), into('vendor/three/LICENSE'))

const ICONS = [
  'sliders-horizontal', 'x', 'move-up-right', 'layers-2', 'route', 'scan', 'focus',
  'circle-check', 'play', 'pause', 'step-forward', 'square', 'rotate-ccw', 'git-branch',
  'archive', 'microwave', 'eye', 'camera', 'chart-column', 'download'
]
const defaults = (await import(pathToFileURL(join(lucide, 'dist/esm/defaultAttributes.js')))).default
const markup = ([tag, attributes, children = []]) => {
  const attrs = Object.entries(attributes).map(([name, value]) => ` ${name}="${value}"`).join('')
  return `<${tag}${attrs}>${children.map(markup).join('')}</${tag}>`
}
const icons = {}
for (const name of ICONS) {
  const [, , children] = (await import(pathToFileURL(join(lucide, `dist/esm/icons/${name}.js`)))).default
  icons[name] = markup(['svg', { ...defaults, class: `lucide lucide-${name}`, 'data-lucide': name, 'aria-hidden': 'true' }, children])
}
writeFileSync(
  into('vendor/lucide/icons.js'),
  `// Generated by tools/vendor-viewer.mjs from lucide (ISC).\nexport const ICONS = ${JSON.stringify(icons, null, 2)}\n`
)
copyFileSync(join(lucide, 'LICENSE'), into('vendor/lucide/LICENSE'))

for (const weight of [400, 500, 700]) {
  const file = `ubuntu-latin-${weight}-normal.woff2`
  copyFileSync(join(ubuntu, 'files', file), into(`fonts/${file}`))
}
copyFileSync(join(ubuntu, 'LICENSE'), into('fonts/LICENSE'))
console.log(`three ${JSON.parse(readFileSync(join(three, 'package.json'), 'utf8')).version}`)
console.log(`lucide ${JSON.parse(readFileSync(join(lucide, 'package.json'), 'utf8')).version}, ${ICONS.length} icons`)
console.log(`ubuntu ${JSON.parse(readFileSync(join(ubuntu, 'package.json'), 'utf8')).version}`)
