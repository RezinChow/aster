// Pack the PX4 Iris CAD meshes for the workbench. MuJoCo collides with the
// frame box in the physics XML; three.js draws these meshes in the body frame.
// The geom quat in iris.xml compensates MuJoCo's mesh loader, so the raw CAD
// is parented with identity here.
import { gzipSync } from 'node:zlib'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = process.argv[2] ?? '/tmp/iris-src/assets/iris/assets'
const out = join(dirname(fileURLToPath(import.meta.url)), '../ui/workbench/vendor/iris/iris.js')

const MESHES = [
  ['iris_frame', 'iris.stl'],
  ['iris_prop_ccw', 'iris_prop_ccw.stl'],
  ['iris_prop_cw', 'iris_prop_cw.stl']
]

function readStl(path) {
  const bytes = readFileSync(path)
  if (bytes.length < 84) throw new Error(`${path} is not an STL`)
  const count = bytes.readUInt32LE(80)
  if (84 + count * 50 !== bytes.length) throw new Error(`${path} is not a binary STL`)
  const vertices = []
  for (let triangle = 0; triangle < count; triangle += 1) {
    const at = 84 + triangle * 50 + 12
    for (let vertex = 0; vertex < 3; vertex += 1) {
      const offset = at + vertex * 12
      vertices.push([bytes.readFloatLE(offset), bytes.readFloatLE(offset + 4), bytes.readFloatLE(offset + 8)])
    }
  }
  return vertices
}

function pack(vertices) {
  const min = [Infinity, Infinity, Infinity]
  const max = [-Infinity, -Infinity, -Infinity]
  for (const vertex of vertices) {
    for (let axis = 0; axis < 3; axis += 1) {
      min[axis] = Math.min(min[axis], vertex[axis])
      max[axis] = Math.max(max[axis], vertex[axis])
    }
  }
  const step = min.map((low, axis) => (max[axis] - low) / 65535 || 0)
  const keyOf = (vertex) =>
    vertex
      .map((value, axis) => (step[axis] === 0 ? 0 : Math.round((value - min[axis]) / step[axis])))
      .join(',')
  const positions = []
  const indexOf = new Map()
  const indices = []
  for (const vertex of vertices) {
    const key = keyOf(vertex)
    let index = indexOf.get(key)
    if (index === undefined) {
      index = positions.length / 3
      indexOf.set(key, index)
      const quantized = key.split(',').map(Number)
      positions.push(quantized[0], quantized[1], quantized[2])
    }
    indices.push(index)
  }
  return { min, step, positions, indices, vertices: positions.length / 3 }
}

const chunks = []
const table = {}
let offset = 0
for (const [name, file] of MESHES) {
  const mesh = pack(readStl(join(root, file)))
  const positionBytes = new Uint16Array(mesh.positions)
  const IndexArray = mesh.vertices > 65535 ? Uint32Array : Uint16Array
  const faceBytes = new IndexArray(mesh.indices)
  chunks.push(Buffer.from(positionBytes.buffer), Buffer.from(faceBytes.buffer))
  table[name] = {
    positions: offset,
    vertices: mesh.vertices,
    faces: offset + positionBytes.byteLength,
    indices: mesh.indices.length,
    wide: IndexArray === Uint32Array,
    min: mesh.min.map((value) => Number(value.toFixed(6))),
    step: mesh.step.map((value) => Number(value.toExponential(8)))
  }
  offset += positionBytes.byteLength + faceBytes.byteLength
  console.log(`${name}: ${mesh.vertices} vertices, ${mesh.indices.length / 3} triangles`)
}

const packed = gzipSync(Buffer.concat(chunks), { level: 9 }).toString('base64')
const visuals = [
  { body: 'base_link', mesh: 'iris_frame', rgba: [0.16, 0.17, 0.19, 1] },
  { body: 'rotor_1_hub', mesh: 'iris_prop_ccw', rgba: [0.75, 0.76, 0.78, 1] },
  { body: 'rotor_2_hub', mesh: 'iris_prop_ccw', rgba: [0.75, 0.76, 0.78, 1] },
  { body: 'rotor_3_hub', mesh: 'iris_prop_cw', rgba: [0.1, 0.1, 0.12, 1] },
  { body: 'rotor_4_hub', mesh: 'iris_prop_cw', rgba: [0.1, 0.1, 0.12, 1] }
]
writeFileSync(
  out,
  `// Quantized PX4 Iris CAD meshes. Generated by tools/vendor-iris.mjs.\n` +
    `export const MESHES = ${JSON.stringify(table)}\n` +
    `export const VISUALS = ${JSON.stringify(visuals)}\n` +
    `export const PACK = ${JSON.stringify(packed)}\n`
)
console.log(`wrote ${out} (${packed.length} base64 chars)`)
