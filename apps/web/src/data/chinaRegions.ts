const provinceById = new Map(PROVINCES.map((item) => [item.id, item]));

function fold(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, '');
}

function samePlace(place: RegionPlace, raw: string): boolean {
  const value = fold(raw);
  return place.id === value || fold(place.zh) === value || fold(place.en) === value;
}

export function provinceOf(id: string): Province | undefined {
  return provinceById.get(id);
}

export function cityOf(provinceId: string, cityId: string): RegionPlace | undefined {
  return provinceOf(provinceId)?.cities.find((item) => item.id === cityId);
}

export function placeName(place: RegionPlace | undefined, locale: 'zh' | 'en'): string {
  if (!place) return '';
  return locale === 'en' ? place.en : place.zh;
}

/** Empty input stays empty. Unknown text returns null. */
export function resolveTerritory(
  provinceRaw: string,
  cityRaw: string,
): { ok: true; province: string; city: string } | { ok: false; issue: 'province' | 'city' } {
  const provinceText = provinceRaw.trim();
  const cityText = cityRaw.trim();
  if (!provinceText && !cityText) return { ok: true, province: '', city: '' };
  const province = provinceText
    ? PROVINCES.find((item) => samePlace(item, provinceText))
    : undefined;
  if (provinceText && !province) return { ok: false, issue: 'province' };
  if (!cityText) return { ok: true, province: province?.id ?? '', city: '' };
  if (province) {
    const city = province.cities.find((item) => samePlace(item, cityText));
    if (!city) return { ok: false, issue: 'city' };
    return { ok: true, province: province.id, city: city.id };
  }
  const hits = PROVINCES.flatMap((item) =>
    item.cities.filter((city) => samePlace(city, cityText)).map((city) => ({
      province: item.id,
      city: city.id,
    })),
  );
  if (hits.length !== 1) return { ok: false, issue: 'city' };
  return { ok: true, province: hits[0]?.province ?? '', city: hits[0]?.city ?? '' };
}
